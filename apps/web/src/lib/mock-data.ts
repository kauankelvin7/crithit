export function buildMockArticleDetail(slug: string): PublicArticleDetail | null {
  const found = MOCK_ARTICLES.find((a) => a.slug === slug);
  if (!found) return null;
  const related = MOCK_ARTICLES.filter((a) => a.slug !== slug && a.category === found.category)
    .concat(MOCK_ARTICLES.filter((a) => a.slug !== slug && a.category !== found.category))
    .slice(0, 4)
    .map(toSummary);
  return {
    ...found,
    relatedArticles: related,
  };
}

export function buildMockReelsResponse(
  category?: Category,
  focusSlug?: string,
): ReelsFeedResponse {
  const filtered = category
    ? MOCK_ARTICLES.filter((a) => a.category === category)
    : MOCK_ARTICLES;
  const items = filtered.map(toSummary);
  const focusSlugFound = focusSlug ? items.some((i) => i.slug === focusSlug) : true;
  return {
    items,
    page: 0,
    size: items.length,
    totalElements: items.length,
    hasNext: false,
    focusSlugFound,
  };
}
